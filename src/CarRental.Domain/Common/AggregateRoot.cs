using System.Diagnostics.CodeAnalysis;

namespace CarRental.Domain.Common;

/// <summary>
/// Consistency boundary: every state change goes through a method of the aggregate that checks its invariants
/// and raises a domain event. Persistence conventions applied to every aggregate:
/// a SQL Server <c>rowversion</c> concurrency token and domain events copied to the outbox on save.
/// </summary>
public abstract class AggregateRoot : Entity
{
    private readonly List<IDomainEvent> _domainEvents = [];

    protected AggregateRoot(Guid id)
        : base(id)
    {
    }

    /// <summary>Used by EF Core when materializing.</summary>
    protected AggregateRoot()
    {
    }

    /// <summary>Optimistic concurrency token, generated by the database (SQL Server <c>rowversion</c>).</summary>
    [SuppressMessage("Performance", "CA1819:Properties should not return arrays", Justification = "EF Core maps SQL Server rowversion to byte[].")]
    public byte[] RowVersion { get; private set; } = null!;

    /// <summary>Events raised since the aggregate was loaded, not yet written to the outbox.</summary>
    public IReadOnlyList<IDomainEvent> DomainEvents => _domainEvents;

    /// <summary>Returns the pending events and clears them (called by the persistence layer when saving).</summary>
    public IReadOnlyList<IDomainEvent> DequeueDomainEvents()
    {
        var events = _domainEvents.ToArray();
        _domainEvents.Clear();
        return events;
    }

    protected void Raise(IDomainEvent domainEvent)
    {
        ArgumentNullException.ThrowIfNull(domainEvent);
        _domainEvents.Add(domainEvent);
    }
}
