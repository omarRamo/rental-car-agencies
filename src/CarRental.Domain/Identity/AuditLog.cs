using CarRental.Domain.Common;

namespace CarRental.Domain.Identity;

/// <summary>
/// An append-only audit record: an entity change (with before/after values) or an explicit security event
/// (login, lockout, user administration). Rows are never updated nor deleted; this is enforced by the persistence
/// layer and by a database trigger.
/// </summary>
public sealed class AuditLog
{
    public const int ActionMaxLength = 64;
    public const int EntityTypeMaxLength = 256;
    public const int EntityIdMaxLength = 128;
    public const int DetailsMaxLength = 2000;

    private AuditLog()
    {
    }

    /// <summary>Database identity: gives the total order of the log.</summary>
    public long Id { get; private set; }

    public DateTimeOffset OccurredAtUtc { get; private set; }

    /// <summary>Action code, see <see cref="AuditActions"/>.</summary>
    public string Action { get; private set; } = null!;

    public Guid? UserId { get; private set; }

    public string? UserName { get; private set; }

    public string? IpAddress { get; private set; }

    public string? CorrelationId { get; private set; }

    /// <summary>CLR name of the changed entity (or subject of the event), e.g. <c>Agency</c>.</summary>
    public string? EntityType { get; private set; }

    /// <summary>Key of the changed entity; <see langword="null"/> when generated by the database at insert.</summary>
    public string? EntityId { get; private set; }

    /// <summary>JSON object of the values before the change (modified properties only for updates).</summary>
    public string? Before { get; private set; }

    /// <summary>JSON object of the values after the change (modified properties only for updates).</summary>
    public string? After { get; private set; }

    /// <summary>Human-readable context of an explicit event (never secrets).</summary>
    public string? Details { get; private set; }

    public static AuditLog Record(
        DateTimeOffset occurredAtUtc,
        AuditActor actor,
        string action,
        string? entityType = null,
        string? entityId = null,
        string? before = null,
        string? after = null,
        string? details = null)
    {
        ArgumentNullException.ThrowIfNull(actor);
        ArgumentException.ThrowIfNullOrWhiteSpace(action);

        return new AuditLog
        {
            OccurredAtUtc = occurredAtUtc.ToUniversalTime(),
            Action = Truncate(action, ActionMaxLength)!,
            UserId = actor.UserId,
            UserName = Truncate(actor.UserName, AuditActor.UserNameMaxLength),
            IpAddress = Truncate(actor.IpAddress, AuditActor.IpAddressMaxLength),
            CorrelationId = Truncate(actor.CorrelationId, AuditActor.CorrelationIdMaxLength),
            EntityType = Truncate(entityType, EntityTypeMaxLength),
            EntityId = Truncate(entityId, EntityIdMaxLength),
            Before = before,
            After = after,
            Details = Truncate(details, DetailsMaxLength),
        };
    }

    private static string? Truncate(string? value, int maxLength) =>
        value is null || value.Length <= maxLength ? value : value[..maxLength];
}
