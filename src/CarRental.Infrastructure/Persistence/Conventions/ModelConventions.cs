using System.Linq.Expressions;
using CarRental.Application.Common.Persistence;
using CarRental.Domain.Common;
using CarRental.Domain.Referential;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace CarRental.Infrastructure.Persistence.Conventions;

/// <summary>Model-wide conventions applied after the per-module configurations.</summary>
public static class ModelConventions
{
    /// <summary>Name of the global query filter that hides soft-deleted rows (<c>IgnoreQueryFilters([ModelConventions.SoftDeleteFilter])</c>).</summary>
    public const string SoftDeleteFilter = QueryFilters.SoftDelete;

    /// <summary>
    /// Name of the global query filter that hides the rows of the other agencies (ADR-0067). Only a platform query run
    /// across agencies on purpose may lift it: <c>IgnoreQueryFilters([ModelConventions.AgencyFilter])</c>.
    /// </summary>
    public const string AgencyFilter = QueryFilters.Agency;

    /// <summary>
    /// <list type="bullet">
    /// <item>Entity ids are generated by the domain (<c>Guid.CreateVersion7()</c>), never by the database.</item>
    /// <item>Aggregates get a <c>rowversion</c> concurrency token; their pending domain events are not mapped.</item>
    /// <item><see cref="ISoftDeletable"/> entities get the named query filter <see cref="SoftDeleteFilter"/>.</item>
    /// <item><see cref="IAgencyOwned"/>, <see cref="IAgencyShared"/> and <see cref="IAgencyOrPlatform"/> entities, and <see cref="Agency"/> itself, get the
    /// named query filter <see cref="AgencyFilter"/>, read from <paramref name="context"/> at each query.</item>
    /// </list>
    /// </summary>
    public static void ApplyCarRentalConventions(this ModelBuilder modelBuilder, CarRentalDbContext context)
    {
        ArgumentNullException.ThrowIfNull(modelBuilder);
        ArgumentNullException.ThrowIfNull(context);

        foreach (var entityType in modelBuilder.Model.GetEntityTypes().Where(t => t.BaseType is null && !t.IsOwned()).ToList())
        {
            var clrType = entityType.ClrType;
            var entity = modelBuilder.Entity(clrType);

            if (typeof(Entity).IsAssignableFrom(clrType))
            {
                entity.Property(nameof(Entity.Id)).ValueGeneratedNever();
            }

            if (typeof(AggregateRoot).IsAssignableFrom(clrType))
            {
                entity.Ignore(nameof(AggregateRoot.DomainEvents));
                entity.Property(nameof(AggregateRoot.RowVersion)).IsRowVersion();
            }

            if (typeof(ISoftDeletable).IsAssignableFrom(clrType))
            {
                entity.HasQueryFilter(SoftDeleteFilter, SoftDeleteFilterFor(clrType));
            }

            if (AgencyFilterFor(clrType, context) is { } agencyFilter)
            {
                entity.HasQueryFilter(AgencyFilter, agencyFilter);
            }
        }
    }

    /// <summary>
    /// <c>e =&gt; !context.AgencyFilterEnabled || e.AgencyId == context.AgencyFilterId</c> for agency data (the shared rows of
    /// <see cref="IAgencyShared"/> entities stay visible, the platform rows of <see cref="IAgencyOrPlatform"/> ones do not,
    /// an <see cref="Agency"/> is matched by its id); <see langword="null"/> for platform data. EF Core reads the context properties of the context that runs the query.
    /// </summary>
    internal static LambdaExpression? AgencyFilterFor(Type clrType, CarRentalDbContext context)
    {
        var entity = Expression.Parameter(clrType, "e");
        var contextConstant = Expression.Constant(context);
        var enabled = Expression.Property(contextConstant, nameof(CarRentalDbContext.AgencyFilterEnabled));
        var agencyId = Expression.Property(contextConstant, nameof(CarRentalDbContext.AgencyFilterId));

        Expression? visible;
        if (clrType == typeof(Agency))
        {
            visible = Expression.Equal(Expression.Property(entity, nameof(Agency.Id)), agencyId);
        }
        else if (typeof(IAgencyOwned).IsAssignableFrom(clrType))
        {
            visible = Expression.Equal(Expression.Property(entity, nameof(IAgencyOwned.AgencyId)), agencyId);
        }
        else if (typeof(IAgencyShared).IsAssignableFrom(clrType))
        {
            var owner = Expression.Property(entity, nameof(IAgencyShared.AgencyId));
            visible = Expression.OrElse(
                Expression.Equal(owner, Expression.Constant(null, typeof(Guid?))),
                Expression.Equal(owner, Expression.Convert(agencyId, typeof(Guid?))));
        }
        else if (typeof(IAgencyOrPlatform).IsAssignableFrom(clrType))
        {
            visible = Expression.Equal(
                Expression.Property(entity, nameof(IAgencyOrPlatform.AgencyId)),
                Expression.Convert(agencyId, typeof(Guid?)));
        }
        else
        {
            return null;
        }

        return Expression.Lambda(Expression.OrElse(Expression.Not(enabled), visible), entity);
    }

    /// <summary>
    /// Maps the entity to a system-versioned temporal table with a history table <c>{name}History</c> in the same schema
    /// (ADR-0003). One line per aggregate that needs "state at any date".
    /// </summary>
    public static EntityTypeBuilder<TEntity> ToTemporalTable<TEntity>(this EntityTypeBuilder<TEntity> builder, string name, string schema)
        where TEntity : class
    {
        ArgumentNullException.ThrowIfNull(builder);
        ArgumentException.ThrowIfNullOrWhiteSpace(name);
        ArgumentException.ThrowIfNullOrWhiteSpace(schema);

        return builder.ToTable(name, schema, table => table.IsTemporal(temporal =>
        {
            temporal.HasPeriodStart("ValidFrom");
            temporal.HasPeriodEnd("ValidTo");
            temporal.UseHistoryTable($"{name}History", schema);
        }));
    }

    private static LambdaExpression SoftDeleteFilterFor(Type clrType)
    {
        var entity = Expression.Parameter(clrType, "e");
        var isDeleted = Expression.Property(entity, nameof(ISoftDeletable.IsDeleted));
        return Expression.Lambda(Expression.Not(isDeleted), entity);
    }
}
